<?php

namespace Javaabu\Mediapicker\Conversions;

use Spatie\MediaLibrary\MediaCollections\Models\Media;

/**
 * What was generated for each attachment conversion of a media, kept in its custom
 * properties under `attachment_conversions.{conversion}-{fingerprint}`:
 *
 * ```php
 * ['width' => 800, 'height' => 450, 'formats' => ['jpg', 'avif', 'webp'], 'widths' => [640, 480, 320]]
 * ```
 */
class ConversionMetadata
{
    public const string PROPERTY = 'attachment_conversions';

    /**
     * @return array{width?: int, height?: int, formats?: array<int, string>, widths?: array<int, int>}|null
     */
    public static function get(Media $media, string $key): ?array
    {
        $metadata = $media->getCustomProperty(self::PROPERTY . ".{$key}");

        return is_array($metadata) ? $metadata : null;
    }

    public static function has(Media $media, string $key): bool
    {
        return static::get($media, $key) !== null;
    }

    /**
     * @return array<string, array<string, mixed>>
     */
    public static function all(Media $media): array
    {
        return $media->getCustomProperty(self::PROPERTY, []);
    }

    /**
     * Record a generated conversion. Reads the media again first, so conversions generated by
     * parallel jobs aren't lost.
     *
     * @param  array<string, mixed>  $metadata
     */
    public static function put(Media $media, string $key, array $metadata): void
    {
        $fresh = $media->exists ? ($media->fresh() ?? $media) : $media;

        $all = static::all($fresh);
        $all[$key] = $metadata;

        $fresh->setCustomProperty(self::PROPERTY, $all);
        $fresh->saveQuietly();

        $media->setCustomProperty(self::PROPERTY, $all);
    }

    /**
     * Forget conversions, e.g. after their files were removed
     *
     * @param  array<int, string>  $keys
     */
    public static function forget(Media $media, array $keys): void
    {
        $fresh = $media->exists ? ($media->fresh() ?? $media) : $media;

        $all = array_diff_key(static::all($fresh), array_flip($keys));

        $fresh->setCustomProperty(self::PROPERTY, $all);
        $fresh->saveQuietly();

        $media->setCustomProperty(self::PROPERTY, $all);
    }
}
